/**
 * Generates supabase/seed.sql from the committed snapshot so the CMS starts
 * with exactly what the site currently shows. Run: npm run seed:sql
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { contentSchema } from '../src/schemas/content.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const content = contentSchema.parse(
  JSON.parse(readFileSync(path.join(root, 'src/data/generated/content.json'), 'utf8')),
)

// Dollar-quoting avoids any escaping issues inside the JSON documents.
const TAG = '$json$'
const json = (v: unknown) => `${TAG}${JSON.stringify(v)}${TAG}::jsonb`
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`

const rows = (table: string, items: { id: string }[]) =>
  items.length
    ? `insert into public.${table} (id, data, sort_order, status) values\n` +
      items.map((item, i) => `  (${lit(item.id)}, ${json(item)}, ${i}, 'published')`).join(',\n') +
      `\non conflict (id) do update set data = excluded.data, sort_order = excluded.sort_order;\n`
    : ''

const sql = `-- Generated by scripts/seed-sql.ts — do not edit by hand.
insert into public.profile (id, data) values (1, ${json(content.profile)})
on conflict (id) do update set data = excluded.data;

${rows('projects', content.projects)}
${rows('badges', content.badges)}
${rows('experiences', content.experiences)}`

writeFileSync(path.join(root, 'supabase/seed.sql'), sql)
console.log('[seed-sql] ✓ wrote supabase/seed.sql')
